import { pathToFileURL } from 'node:url';
import { createServer } from './server.mjs';
const HELPER = 'C:/Users/35238/.agents/skills/ai-daily-video/scripts/chrome.mjs';
const server = createServer();
await new Promise(r => server.listen(0, '127.0.0.1', r));
const base = 'http://127.0.0.1:' + server.address().port;
const mod = await import(pathToFileURL(HELPER).href);
const browser = await mod.launch();
const page = await browser.newPage();
await page.setViewport({ width: 1560, height: 900 });
page.on('pageerror', e => console.log('PAGEERROR', e.message));
await page.goto(base + '/', { waitUntil: 'load' });
await page.waitForSelector('#cover .cv');
await new Promise(r => setTimeout(r, 1200));
await page.evaluate(async function () {
  App.toast = function () {};
  const c = document.createElement('canvas'); c.width = 900; c.height = 600;
  const g = c.getContext('2d');
  const grad = g.createLinearGradient(0, 0, 900, 600); grad.addColorStop(0, '#0f2a4d'); grad.addColorStop(1, '#7a1f3d');
  g.fillStyle = grad; g.fillRect(0, 0, 900, 600);
  g.fillStyle = 'rgba(255,255,255,.85)'; g.font = 'bold 90px sans-serif'; g.fillText('BG TEST', 120, 330);
  const blob = await new Promise(function (res) { c.toBlob(res, 'image/png'); });
  const file = new File([blob], 'bg.png', { type: 'image/png' });
  App.pickImage(file, true);
});
await new Promise(r => setTimeout(r, 1500));
const imgInfo = await page.evaluate(function () {
  var L = App.doc.layers;
  var first = L[0];
  var el = document.querySelector('#cover .cv-image');
  var im = el && el.querySelector('img');
  return JSON.stringify({ layers: L.length, firstType: first && first.type, role: first && first.role, srcLen: first && first.src ? first.src.length : 0, hasData: !!(im && im.src.indexOf('data:') === 0), w: first && first.w, h: first && first.h });
});
console.log('背景图 =', imgInfo);
await page.evaluate("App.setRatio('xhs')");
await new Promise(r => setTimeout(r, 500));
const fit = await page.evaluate(function () { var el = document.querySelector('#cover .cv-image'); return el ? JSON.stringify({ w: el.offsetWidth, h: el.offsetHeight }) : 'none'; });
console.log('3:4 下背景尺寸 =', fit);
await page.evaluate('App.exportHtml()');
await new Promise(r => setTimeout(r, 2500));
const html = await page.evaluate('App.__lastHtml ? App.__lastHtml.length : 0');
const checks = await page.evaluate(function () {
  var h = App.__lastHtml || '';
  return JSON.stringify({ len: h.length, hasCv: h.indexOf('class="cv') > -1, hasDataImg: h.indexOf('data:image') > -1, hasTex: h.indexOf('data:image/png;base64') > -1, hasStyle: h.indexOf('<style>') > -1, hasInlineCss: h.indexOf('.cv-text') > -1 });
});
console.log('导出 HTML =', checks);
const cvb = await (await page.$('#cover .cv')).boundingBox();
await page.screenshot({ path: 'out/qa/_bg-image.png', clip: { x: cvb.x, y: cvb.y, width: cvb.width, height: cvb.height } });
const ok = (html > 5000) && JSON.parse(checks).hasDataImg && JSON.parse(checks).hasInlineCss;
console.log(ok ? 'PASS 图片背景 + HTML 导出' : 'FAIL');
await browser.close();
server.close();
process.exit(0);
import { pathToFileURL } from 'node:url';
import { createServer } from './server.mjs';
const HELPER = 'C:/Users/35238/.agents/skills/ai-daily-video/scripts/chrome.mjs';
const server = createServer();
await new Promise(r => server.listen(0, '127.0.0.1', r));
const base = 'http://127.0.0.1:' + server.address().port;
const mod = await import(pathToFileURL(HELPER).href);
const browser = await mod.launch();
const page = await browser.newPage();
await page.setViewport({ width: 1560, height: 900 });
await page.goto(base + '/', { waitUntil: 'load' });
await page.waitForSelector('#cover .cv');
await new Promise(r => setTimeout(r, 1400));
await page.click('.panel.left .tab[data-tab="style"]');
await new Promise(r => setTimeout(r, 700));
console.log('layouts rendered =', await page.evaluate('document.querySelectorAll("#layoutGrid .lay").length'));
console.log('style cards =', await page.evaluate('document.querySelectorAll(".style-card").length'));
await page.screenshot({ path: 'out/qa/_ui-style.png' });
await page.evaluate("App.setRatio('xhs')");
await new Promise(r => setTimeout(r, 800));
console.log('portrait layouts =', await page.evaluate('document.querySelectorAll("#layoutGrid .lay").length'));
await page.screenshot({ path: 'out/qa/_ui-portrait.png' });
await browser.close();
server.close();
process.exit(0);
/* 快速冒烟：资源是否全部加载、画布是否渲染、出图兜底是否生效 */
import { pathToFileURL } from 'node:url';
import { createServer } from './server.mjs';
const HELPER = 'C:/Users/35238/.agents/skills/ai-daily-video/scripts/chrome.mjs';
const server = createServer();
await new Promise(r => server.listen(0, '127.0.0.1', r));
const base = 'http://127.0.0.1:' + server.address().port;
const mod = await import(pathToFileURL(HELPER).href);
const browser = await mod.launch();
const page = await browser.newPage();
await page.setViewport({ width: 1560, height: 900 });
const bad = [];
page.on('pageerror', e => bad.push('pageerror: ' + e.message));
page.on('requestfailed', r => { const u = r.url(); if (u.indexOf('fonts.gstatic') < 0 && u.indexOf('fonts.googleapis') < 0) bad.push('reqfail: ' + u); });
page.on('response', r => { if (r.status() >= 400 && r.url().indexOf(base) === 0) bad.push('http' + r.status() + ': ' + r.url().replace(base, '')); });
await page.goto(base + '/', { waitUntil: 'load' });
await page.waitForSelector('#cover .cv', { timeout: 15000 });
await new Promise(r => setTimeout(r, 1500));
const n = await page.evaluate('document.querySelectorAll("#cover .cv-el").length');
const styles = await page.evaluate('window.CV.STYLES.length');
const icons = await page.evaluate('typeof Panels !== "undefined" ? document.querySelectorAll("#iconList .ictile").length : -1');
const fontOk = await page.evaluate('document.fonts.check("900 40px CV-Heavy")');
console.log('layers=' + n + ' styles=' + styles + ' iconTiles=' + icons + ' heavyFont=' + fontOk);
await page.evaluate('App.recompose({style:"newspaper",layout:"hero"})');
await new Promise(r => setTimeout(r, 400));
await page.evaluate('App.recompose({style:"zine",layout:"hero"})');
await new Promise(r => setTimeout(r, 400));
console.log(bad.length ? 'PROBLEMS:\n  ' + bad.slice(0, 12).join('\n  ') : 'PASS 无失败请求/JS 错误');
await browser.close();
server.close();
process.exit(bad.length ? 1 : 0);
